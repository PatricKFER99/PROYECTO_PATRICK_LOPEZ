-- 1. TABLA DE PRODUCTOS (Categorías 1, 2, 3 = Catálogo | Categoría 4 = Promociones)
CREATE TABLE IF NOT EXISTS public.t_producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10, 2) NOT NULL,
    id_catalogo INTEGER NOT NULL DEFAULT 1,
    imagen TEXT,
    fecha_creacion TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABLA DE CLIENTES (Registro e Inicio de Sesión)
CREATE TABLE IF NOT EXISTS public.t_cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo TEXT NOT NULL,
    apellido_paterno TEXT,
    apellido_materno TEXT,
    telefono TEXT,
    dni VARCHAR(15),
    ruc VARCHAR(20),
    correo TEXT UNIQUE NOT NULL,
    contrasena TEXT NOT NULL,
    fecha_registro TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA DE DISTRITOS (Zonas de reparto / Delivery)
CREATE TABLE IF NOT EXISTS public.t_distrito (
    id_distrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL
);

-- 4. TABLA DE VENTAS (Cabecera de pedidos y comprobantes)
CREATE TABLE IF NOT EXISTS public.t_ventas (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT REFERENCES public.t_cliente(id_cliente) ON DELETE SET NULL,
    id_forma_pago INTEGER NOT NULL,
    id_comprobante INTEGER NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    total NUMERIC(10, 2) NOT NULL,
    estado_orden TEXT DEFAULT 'Recibido',
    id_distrito BIGINT REFERENCES public.t_distrito(id_distrito) ON DELETE SET NULL,
    direccion_envio TEXT NOT NULL,
    id_ano INTEGER,
    id_mes INTEGER,
    id_dia INTEGER,
    fecha_venta TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA DE DETALLE DE VENTA (Productos comprados en cada pedido)
CREATE TABLE IF NOT EXISTS public.t_detalle_venta (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT REFERENCES public.t_ventas(id_venta) ON DELETE CASCADE,
    id_producto BIGINT REFERENCES public.t_producto(id_producto) ON DELETE SET NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL
);

-- 6. TABLA DE CONTACTO Y SOPORTE (Mensajes de clientes)
CREATE TABLE IF NOT EXISTS public.t_contacto (
    id_contacto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    correo TEXT NOT NULL,
    mensaje TEXT NOT NULL,
    fecha TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- PERMISOS AUTOMÁTICOS (Row Level Security abierto para funcionamiento directo)
