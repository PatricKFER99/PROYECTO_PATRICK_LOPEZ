VALUES ('fotos', 'fotos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas para permitir subir, ver, editar y borrar fotos desde el panel Admin
DROP POLICY IF EXISTS "Acceso Publico Fotos Lectura" ON storage.objects;
CREATE POLICY "Acceso Publico Fotos Lectura" ON storage.objects
    FOR SELECT USING (bucket_id = 'fotos');

DROP POLICY IF EXISTS "Acceso Publico Fotos Subida" ON storage.objects;
CREATE POLICY "Acceso Publico Fotos Subida" ON storage.objects
    FOR INSERT WITH CHECK (bucket_id = 'fotos');

DROP POLICY IF EXISTS "Acceso Publico Fotos Edicion" ON storage.objects;
CREATE POLICY "Acceso Publico Fotos Edicion" ON storage.objects
    FOR UPDATE USING (bucket_id = 'fotos');

DROP POLICY IF EXISTS "Acceso Publico Fotos Borrado" ON storage.objects;
CREATE POLICY "Acceso Publico Fotos Borrado" ON storage.objects
    FOR DELETE USING (bucket_id = 'fotos');

