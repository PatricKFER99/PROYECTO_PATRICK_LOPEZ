ALTER TABLE public.t_producto DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_cliente DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_distrito DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_ventas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_detalle_venta DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_contacto DISABLE ROW LEVEL SECURITY;

